pub fn build_filter(keys: &[&str]) -> Option<BsonDoc> {
    if keys.is_empty() {
        return None;
    }
    Some(keys.iter().map(|k| (k.to_string(), BsonVal::Str("…".into()))).collect())
}

pub fn build_pipeline(stages: &[&str]) -> Option<Vec<BsonDoc>> {
    if stages.is_empty() {
        return None;
    }
    Some(
        stages
            .iter()
            .map(|s| {
                let mut doc = IndexMap::new();
                doc.insert(s.to_string(), BsonVal::Doc(IndexMap::new()));
                doc
            })
            .collect(),
    )
}
